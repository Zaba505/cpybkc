package main

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/Zaba505/cpybkc/irpb"
)

// The one file a run writes, named for the notation it is written in.
//
// The names are fixed rather than derived, and there is no option to change
// them: the descriptor carries no name for the layout it describes, and
// docs/plugin/SPEC.md's "The descriptor" forbids deriving anything from the
// descriptor's own path or the directory holding it. The output directory's
// name is cpybkc's to choose and varies between runs, so a filename taken from
// it would make the output a function of a path — which is what "Determinism"
// forbids. What is left is a constant, and one document per run is what this
// generator produces.
const (
	mermaidFile = "graph.md"
	dotFile     = "graph.dot"
)

// generatedBy is the line that says a file was not written by hand, in each
// notation's own comment syntax.
//
// Go's own tooling matches `^// Code generated .* DO NOT EDIT\.$` and neither
// of these files is Go, but the sentence is the one a reader of a diff already
// knows, and the Markdown document carries it as an HTML comment so that it
// does not render.
const (
	generatedBy = "Code generated by " + pluginName + ". DO NOT EDIT."

	mermaidGeneratedBy = "<!-- " + generatedBy + " -->"
	dotGeneratedBy     = "// " + generatedBy
)

// write writes this invocation's document beneath out.
//
// docs/plugin/SPEC.md's "Determinism" is met by there being nothing in the
// output that is not a function of the descriptor and the options: no
// timestamp, no hostname, no user, no absolute path, and no value read from
// anywhere but the arguments. The generator's own name is in the output and is
// allowed to be — it is a property of the executable rather than of the
// invocation, and output that changes when the generator is upgraded is
// expected.
//
// The document is composed whole and then written, so that a descriptor this
// generator refuses leaves the output directory as it found it — empty. A
// generator that wrote as it went would hand cpybkc a directory it is entitled
// to merge, holding half a document.
func write(descriptor *irpb.Descriptor, out string, opts options) error {
	name, content, err := document(descriptor, opts)
	if err != nil {
		return err
	}

	// Written directly beneath out, and beneath it only: docs/plugin/SPEC.md
	// gives this program an empty, writable directory of its own and forbids it
	// to write anywhere else. The path is joined here rather than anywhere a
	// file name could arrive from outside this program.
	if err := os.WriteFile(filepath.Join(out, name), []byte(content), 0o644); err != nil {
		return fmt.Errorf("failed to write %s: %w", name, err)
	}

	return nil
}

// document is the file this invocation writes: its name, and its whole
// contents.
//
// # What it draws today
//
// Nothing. The diagram this generator exists for — the sequencing automaton,
// with each record's items beneath the state that reads it — is the story after
// this one, and what is here is an empty document in the notation the
// invocation asked for: valid for a renderer to load, and carrying no state,
// no transition and no record.
//
// That is deliberate rather than unfinished. This generator is the first
// consumer of docs/plugin/SPEC.md that did not ship with it, and the argument
// vector, the version check, the diagnostic format and the option vocabulary
// are what make it one. Writing the document from the commit that adds the
// executable is what puts it on the contract — a zero exit means the file the
// plugin intended to produce is written and closed beneath `--out` — before
// there is anything to say inside it, so that the commit that fills it in is a
// change to this function and to nothing else.
//
// The descriptor is a parameter for the same reason: it is what the diagram is
// read out of, and a signature that took only the options would have to change
// in the same commit that gives this something to draw.
//
// # Why the default arm is a failure rather than a notation
//
// [parse] admits exactly the two formats below and defaults the option, so the
// last arm cannot be reached from an argument vector. It is a failure anyway,
// because the way it *would* be reached is a third format added to the closed
// set with no arm added here — and the alternative to failing is writing a
// Mermaid document under the Mermaid filename for a caller who asked for
// something else. That is the "silently rounded to a default" outcome the
// option vocabulary refuses on the way in, and it would be worse arriving on
// the way out, where nothing is left to say it happened.
func document(descriptor *irpb.Descriptor, opts options) (string, string, error) {
	switch opts.format {
	case formatDot:
		// The graph is named for this project rather than for the layout,
		// because the descriptor states no name for the layout and the two paths
		// this generator can see are ones it may not read a name out of. `dot`
		// requires a name-or-nothing here and an anonymous digraph is one a
		// reader cannot refer to from a document that embeds it.
		return dotFile, dotGeneratedBy + "\n\ndigraph cpybkc {\n}\n", nil
	case formatMermaid:
		// Markdown rather than a bare `.mmd`, because the notation's whole
		// advantage is that a forge renders it in a diff, and what a forge
		// renders is a fenced block in a document.
		return mermaidFile, mermaidGeneratedBy + "\n\n```mermaid\nstateDiagram-v2\n```\n", nil
	default:
		return "", "", fmt.Errorf("this generator has no document for %s=%q, which is a bug in %s",
			formatOption, opts.format, pluginName)
	}
}
