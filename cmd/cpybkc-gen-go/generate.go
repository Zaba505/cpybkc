package main

import (
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"sort"

	"github.com/Zaba505/cpybkc/irpb"
)

// generatedFile is the package's doc file, carrying the package clause and
// nothing else. It is written for every descriptor, including one carrying no
// record node at all: a package that is nothing but a package clause is still a
// package that compiles, which is what makes the output something a user can
// point cpybkc at rather than a program that is not finished.
//
// The record structs land beside it in [recordsFile], the decode and encode
// methods in [codecFile], and the file-level reader and writer in
// [fileMachineFile]. The codec version assertions are #53, and land as a file
// of their own for the same reason.
const generatedFile = "doc.go"

// generatedBy is the line Go's own tooling reads to know a file was not written
// by hand. `^// Code generated .* DO NOT EDIT\.$` is the form cmd/go matches,
// and matching it is what keeps generated output out of a vet run's blame and
// out of a reviewer's way.
const generatedBy = "// Code generated by " + pluginName + ". DO NOT EDIT."

// generate writes this invocation's output beneath out.
//
// docs/plugin/SPEC.md's "Determinism" is met by there being nothing in the
// output that is not a function of the descriptor and the options: no
// timestamp, no hostname, no user, no absolute path, and no value read from
// anywhere but the arguments. The generator's own name is in the output and is
// allowed to be — it is a property of the executable rather than of the
// invocation, and output that changes when the generator is upgraded is
// expected.
//
// Every file is composed and formatted before any is written, so that a
// descriptor this generator refuses leaves the output directory as it found it
// — empty. A generator that wrote as it went would hand cpybkc a directory it
// is entitled to merge, holding half a package.
//
// # What is composed first, and why that decides a refusal
//
// The four files that are the package are composed before either tier of tests,
// and that order is what [advisory] rests on: a descriptor whose synthesizer is
// reached at all is one this generator has already emitted a reader and a writer
// for. So a construct the synthesizer cannot lay out bytes for costs its test
// and nothing else — the four files are exactly what they would have been, and
// w carries a `warning:` naming the construct. See README.md, "When a descriptor
// admits no checkable file".
//
// w is the diagnostic channel rather than a return value because a generation
// that skipped a case still succeeded: there is no error to return and there is
// something to say.
func generate(w io.Writer, descriptor *irpb.Descriptor, out string, opts options) error {
	sources := map[string]string{
		generatedFile: fmt.Sprintf("%s\n\npackage %s\n", generatedBy, opts.packageName),
	}

	structs, err := records(descriptor, opts)
	if err != nil {
		return err
	}

	// Absent, rather than a file holding a package clause and no declaration,
	// where the descriptor carries no record node. There is nothing in such a
	// file that doc.go does not already say.
	if structs != "" {
		sources[recordsFile] = structs
	}

	methods, err := codecMethods(descriptor, opts)
	if err != nil {
		return err
	}

	// Absent for the same reason and by the same test: methods on no types are
	// nothing.
	if methods != "" {
		sources[codecFile] = methods
	}

	// The record tier of the generated tests, written exactly when the two
	// files it covers are and turned off by nothing: there is no `tests=`
	// option, because an adopter who has to discover a flag is an adopter who
	// never gets the spot-check the literal exists to be. See README.md,
	// "Decided: the test files are written unconditionally".
	tests, recordSkips, err := recordTests(descriptor, opts)
	if err != nil {
		return err
	}

	if tests != "" {
		sources[recordsTestFile] = tests
	}

	machine, err := fileMachine(descriptor, opts)
	if err != nil {
		return err
	}

	// Absent where the descriptor's automaton admits no record, which is a
	// descriptor describing no record stream: there is no framing to consume
	// and no walk to make, so a reader and a writer would be a pair of types
	// with nothing to read or write.
	if machine != "" {
		sources[fileMachineFile] = machine
	}

	// The file tier, written exactly when the file it covers is and by the same
	// test: a tier over a reader and a writer that were not emitted has nothing
	// to cover.
	files, fileSkips, err := fileTests(descriptor, opts)
	if err != nil {
		return err
	}

	if files != "" {
		sources[fileTestFile] = files
	}

	names := make([]string, 0, len(sources))
	for name := range sources {
		names = append(names, name)
	}

	sort.Strings(names)

	formatted := make(map[string][]byte, len(sources))

	for _, name := range names {
		// Formatted rather than trusted to be formatted. It is the check that
		// makes "generated code is gofmt-clean" a property of the program
		// rather than of whoever wrote the template that produced it, and on a
		// struct emitter it is also what decides the indentation, so that
		// nothing here has to count tabs.
		b, err := format.Source([]byte(sources[name]))
		if err != nil {
			return fmt.Errorf("failed to format the generated %s: %w", name, err)
		}

		formatted[name] = b
	}

	for _, name := range names {
		// Written directly beneath out, and beneath it only: docs/plugin/SPEC.md
		// gives this program an empty, writable directory of its own and forbids
		// it to write anywhere else. The path is joined here rather than anywhere
		// a file name could arrive from outside this program.
		if err := os.WriteFile(filepath.Join(out, name), formatted[name], 0o644); err != nil {
			return fmt.Errorf("failed to write %s: %w", name, err)
		}
	}

	// After the files rather than as each tier is composed, because every one of
	// these lines says the package was generated anyway and that is a sentence
	// this program is only entitled to say once the package is on disk. A
	// generation that failed after a tier was skipped writes no warning at all:
	// it wrote no package for the warning to be about.
	reportSkips(w, append(recordSkips, fileSkips...))

	return nil
}
