// The assertion that every committed example is what its committed inputs
// produce.
//
// This directory holds a tree of examples rather than one, and each of them is a
// self-contained cpybkc project: a `cpybkc.json` beside the layout it names, the
// copybooks that layout names, and the directories its generators write into.
// README.md says why the manifest is per example rather than one at this level.
//
// Everything inside an example divides in two. The layout, the copybooks and the
// manifest are what a caller writes; the directories the manifest's generators
// write into and `cpybkc.gen.json` are what cpybkc writes for them. These tests
// regenerate the second half from the first, through the real CLI and the real
// generators, and hold every byte of the result against what is checked in —
// for every example, so that a third one is covered by having been added rather
// than by anything here being extended.
//
// It is byte for byte, and it is the whole tree rather than a sample of it,
// because the point of a committed example is that a change to any layer of the
// pipeline — the layout reader, the copybook reader, `resolve`, `assemble`, the
// IR or either emitter — arrives as a diff somebody reviews. A test asserting
// that generation merely *succeeds* would pass on a run that generated the wrong
// thing, which is the failure this whole directory exists to catch.
//
// The second test below is the one that could not be written while a project ran
// one generator: that a run assembles a single descriptor and hands every
// generator in it the same bytes. It needs an example whose manifest names two,
// and it requires at least one of them to exist rather than passing over a tree
// where none does.
//
// Regenerate with the lines README.md gives, and commit the result.
package example

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"slices"
	"strings"
	"testing"
)

// The two halves of this directory, by name.
const (
	// manifestName is the project manifest, which is also the argument the
	// CLI is given.
	manifestName = "cpybkc.json"

	// recordName is the record of what was generated, which cpybkc writes
	// beside the manifest and reads on the next run to prune what a layout
	// no longer describes.
	recordName = "cpybkc.gen.json"
)

// generatedHeader is the line Go's own tooling reads to know a file was not
// written by hand, and the line this test reads to know a `_test.go` file is
// output rather than one of this repository's own.
//
// Spelled out here rather than imported: this package is not the generator's,
// and the form `cmd/go` matches — `^// Code generated .* DO NOT EDIT\.$` — is
// the contract between them rather than a constant either owns.
const generatedHeader = "// Code generated by cpybkc-gen-go. DO NOT EDIT."

// generator is one entry of the manifest's `generators` array, reduced to the
// two fields this test needs: the name cpybkc resolves to an executable, and
// the directory that executable's output lands in.
type generator struct {
	Name string `json:"name"`
	Out  string `json:"out"`
}

// TestEveryCommittedExampleIsWhatItsInputsGenerate regenerates every example
// from the inputs beside it and requires each result byte for byte.
//
// One sub-test per example, so a tree where one example drifted names that
// example rather than reporting a file whose directory a reader has to work out.
func TestEveryCommittedExampleIsWhatItsInputsGenerate(t *testing.T) {
	// No t.Parallel, here or in the sub-tests: this test sets PATH for the
	// process, which is how the generators it just built are the ones the CLI
	// finds.

	for _, example := range examples(t) {
		t.Run(example, func(t *testing.T) {
			regenerates(t, example)
		})
	}
}

// regenerates is [TestEveryCommittedExampleIsWhatItsInputsGenerate] over one
// example.
func regenerates(t *testing.T, example string) {
	t.Helper()

	root := repoRoot(t)
	bin := t.TempDir()
	gens := generators(t, example)

	build(t, root, bin, "./cmd/cpybkc", "cpybkc")

	for _, gen := range gens {
		build(t, root, bin, "./cmd/"+pluginName(gen.Name), pluginName(gen.Name))
	}

	project := t.TempDir()
	for _, name := range inputs(t, example) {
		copyFile(t, filepath.Join(example, name), filepath.Join(project, name))
	}

	// The record of the last generation goes in too, even though it is output
	// rather than an input a caller writes. It is what cpybkc reads to prune a
	// file a layout no longer describes, so a run made without it is not the
	// run the README documents — the prune path would be the one path this
	// test never took, and a change in it would surface as a working-tree diff
	// nobody's test predicted. It spans both generators' output, which is what
	// lets a generator removed from the manifest have its output pruned, so a
	// two-generator run is also the first one to exercise that.
	copyFile(t, filepath.Join(example, recordName), filepath.Join(project, recordName))

	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))

	cmd := exec.Command(filepath.Join(bin, executable("cpybkc")),
		"--manifest", filepath.Join(project, manifestName))

	// The run is made standing in the copy, which is where a person running the
	// documented command stands. cpybkc resolves a manifest's `layout` and `out`
	// against the manifest rather than against the working directory, so this
	// changes nothing today — and that is the point: were it ever to resolve one
	// against the working directory, this test would rewrite the checked-in
	// package and then fail for a reason that named the wrong thing.
	cmd.Dir = project

	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generating the example: %v\n%s", err, out)
	}

	outs := outputDirs(gens)
	generated := generatedTree(t, project, outs)
	committed := generatedTree(t, example, outs)

	for name, want := range committed {
		got, ok := generated[name]
		if !ok {
			t.Errorf("nothing was generated for %s, which the example carries", name)

			continue
		}

		if got != want {
			t.Errorf("the generated %s is not the one checked in%s", name, difference(got, want))
		}
	}

	for name := range generated {
		if _, ok := committed[name]; !ok {
			t.Errorf("%s was generated and the example does not carry it", name)
		}
	}
}

// TestEveryGeneratorInTheRunIsHandedTheSameDescriptor asserts the equality the
// plugin contract rests reproducibility on: every generator in a run is handed
// the same descriptor bytes, and they are the bytes `--emit-ir` writes for the
// same inputs.
//
// docs/plugin/SPEC.md states it and one generator could never show it: with a
// single entry in the manifest there is no second set of bytes to be equal to,
// and "every generator gets the same bytes" holds by there being nothing to
// compare. The ledger example is the first project in the repository that runs
// two, so it is the first place the equality can fail — and this test walks
// every example that runs two, so a second one is covered by having been added.
//
// An example running one generator is not asserted here and is not a failure;
// what would be a failure is the tree holding none that runs two, which the
// caller reports rather than skipping.
//
// # What this does not show
//
// That the run assembled **one** descriptor. Assembly is deterministic over the
// same inputs — the `--emit-ir` half below leans on exactly that, since it
// compares against bytes a second cpybkc process produced — so a pipeline that
// assembled a fresh descriptor per generator would hand both stubs identical
// files and pass this unchanged. Telling those apart would need the number of
// assemblies to be observable, and nothing in the contract makes it so.
//
// That is not a gap being tolerated quietly: the equality is the property the
// contract states and the property a reader reproducing a failing generation
// depends on, and it is what this asserts. How many times the bytes were
// computed is not something anybody downstream can act on.
//
// It is asserted through the contract rather than through the packages behind
// it. Real generators keep the bytes they were handed to themselves, so this
// run puts a stub generator on PATH under every one of the manifest's names: it
// copies the file at `--descriptor` into its own `--out` and writes nothing
// else. `--out` is a private scratch directory cpybkc merges into the project
// tree on a zero exit, so the bytes each generator saw arrive in the project
// under that generator's own output directory, with nothing this test has to
// know about where cpybkc put them in the meantime.
func TestEveryGeneratorInTheRunIsHandedTheSameDescriptor(t *testing.T) {
	// No t.Parallel, here or in the sub-tests, for the reason above: PATH is
	// process-wide.

	multiple := 0

	for _, example := range examples(t) {
		if len(generators(t, example)) < 2 {
			continue
		}

		multiple++

		t.Run(example, func(t *testing.T) {
			handedTheSameDescriptor(t, example)
		})
	}

	// The equality needs a project running two generators to hold between
	// anything, and whether the tree still has one is not something a skip should
	// report quietly. An example narrowed to a single generator, or renamed out
	// of this walk, would otherwise take this assertion with it and leave a green
	// run behind.
	if multiple == 0 {
		t.Errorf("no example here runs two generators, and this assertion needs one that does: with a single entry in a %s there is no second set of bytes to be equal to", manifestName)
	}
}

// handedTheSameDescriptor is
// [TestEveryGeneratorInTheRunIsHandedTheSameDescriptor] over one example, which
// its caller has already checked runs at least two generators.
func handedTheSameDescriptor(t *testing.T, example string) {
	t.Helper()

	root := repoRoot(t)
	bin := t.TempDir()
	gens := generators(t, example)

	build(t, root, bin, "./cmd/cpybkc", "cpybkc")

	for _, gen := range gens {
		buildStub(t, bin, pluginName(gen.Name))
	}

	project := t.TempDir()
	for _, name := range inputs(t, example) {
		copyFile(t, filepath.Join(example, name), filepath.Join(project, name))
	}

	// No record goes in. The stubs write one file each and none of the files the
	// committed record names, so carrying it over would ask cpybkc to prune the
	// real output out of a project that never had it.

	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))

	manifest := filepath.Join(project, manifestName)

	cmd := exec.Command(filepath.Join(bin, executable("cpybkc")), "--manifest", manifest)
	cmd.Dir = project

	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("running the stub generators: %v\n%s", err, out)
	}

	// What each generator was handed, in the order the manifest declares them.
	first := gens[0]
	want := readFile(t, filepath.Join(project, first.Out, stubOutput))

	for _, gen := range gens[1:] {
		got := readFile(t, filepath.Join(project, gen.Out, stubOutput))

		if !bytes.Equal(got, want) {
			t.Errorf("the descriptor %s was handed is not the one %s was handed: %d bytes against %d",
				gen.Name, first.Name, len(got), len(want))
		}
	}

	// And that those are the bytes --emit-ir writes for the same inputs, which
	// is the half of the equality a reader reproducing a failing generation by
	// hand depends on. --emit-ir is terminal and runs no generator, so this is a
	// second run over the same manifest.
	emitted := filepath.Join(t.TempDir(), "descriptor.binpb")

	cmd = exec.Command(filepath.Join(bin, executable("cpybkc")),
		"--manifest", manifest, "--emit-ir", emitted)
	cmd.Dir = project

	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("emitting the descriptor: %v\n%s", err, out)
	}

	if got := readFile(t, emitted); !bytes.Equal(got, want) {
		t.Errorf("the descriptor --emit-ir writes is not the one the generators were handed: %d bytes against %d",
			len(got), len(want))
	}
}

// TestTheRecordPrunesEveryGeneratorsOutput asserts that the stale-file pruning
// `cpybkc.gen.json` drives is unaffected by there being two generators.
//
// There is **one** record per project rather than one per generator, and that is
// what lets a generator removed from the manifest have its output pruned — the
// record outlives the entry that produced any of it. With one generator in a
// manifest, a pipeline that kept the record per generator would behave
// identically; with two, it would prune one generator's output while writing the
// other's, or leave a stale file behind in whichever directory it was not
// looking at.
//
// So this run starts from a project whose record names a stale file in *every*
// output directory and nothing else. Every one of them has to be gone
// afterwards, and the record has to come out as the committed one — the run's
// real output, recorded together and sorted across both generators.
//
// One of those stale files is in a directory **no** current generator writes
// into, and it is the one that makes this an assertion about the record rather
// than about the output directories. A pipeline that never read
// `cpybkc.gen.json` at all — one that simply emptied each generator's `out`
// before merging its scratch tree in — would pass on the other two and leave
// this one where it stands. It is also the case the record exists for: a
// generator removed from the manifest has an `out` nothing writes to any more,
// and the record outliving the entry is the whole of what prunes it.
func TestTheRecordPrunesEveryGeneratorsOutput(t *testing.T) {
	// No t.Parallel, here or in the sub-tests, for the reason the tests above
	// give: PATH is process-wide.

	for _, example := range examples(t) {
		t.Run(example, func(t *testing.T) {
			prunes(t, example)
		})
	}
}

// prunes is [TestTheRecordPrunesEveryGeneratorsOutput] over one example.
func prunes(t *testing.T, example string) {
	t.Helper()

	root := repoRoot(t)
	bin := t.TempDir()
	gens := generators(t, example)

	build(t, root, bin, "./cmd/cpybkc", "cpybkc")

	for _, gen := range gens {
		build(t, root, bin, "./cmd/"+pluginName(gen.Name), pluginName(gen.Name))
	}

	project := t.TempDir()
	for _, name := range inputs(t, example) {
		copyFile(t, filepath.Join(example, name), filepath.Join(project, name))
	}

	// A stale file in each output directory and one in a directory no generator
	// in this manifest writes into, and a record that names them and nothing
	// else. They are what the last run is being said to have generated, so this
	// run has to prune every one of them.
	const (
		staleName = "stale.txt"

		// retiredDir stands for the `out` of a generator that has since been
		// taken out of the manifest. Nothing this run does goes near it.
		retiredDir = "retired"
	)

	var stale []string

	for _, dir := range append(outputDirs(gens), retiredDir) {
		if err := os.MkdirAll(filepath.Join(project, dir), 0o755); err != nil {
			t.Fatalf("making %s: %v", dir, err)
		}

		path := filepath.Join(project, dir, staleName)
		if err := os.WriteFile(path, []byte("what the last run is said to have written\n"), 0o644); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		stale = append(stale, dir+"/"+staleName)
	}

	writeRecord(t, filepath.Join(project, recordName), stale)

	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))

	cmd := exec.Command(filepath.Join(bin, executable("cpybkc")),
		"--manifest", filepath.Join(project, manifestName))
	cmd.Dir = project

	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("regenerating over a stale record: %v\n%s", err, out)
	}

	for _, name := range stale {
		if _, err := os.Stat(filepath.Join(project, filepath.FromSlash(name))); !errors.Is(err, fs.ErrNotExist) {
			t.Errorf("%s survived a run whose record named it and whose generators did not write it: %v", name, err)
		}
	}

	got := readFile(t, filepath.Join(project, recordName))
	if want := readFile(t, filepath.Join(example, recordName)); !bytes.Equal(got, want) {
		t.Errorf("the record a pruning run wrote is not the one checked in\n got: %s\nwant: %s", got, want)
	}
}

// indexName is the index this directory's README is, and the one file here that
// names the examples in prose rather than by walking for them.
const indexName = "README.md"

// TestTheIndexNamesEveryExample holds README.md's table of examples against the
// tree the tests above walk.
//
// It is the one place in this directory that is a list rather than a listing,
// and the README says two lines under the table that "adding one is adding a
// directory: everything below reads the tree rather than a list". Everything
// below does. The table cannot, because a one-line description of what an
// example is *for* is not derivable from the example — so the way to keep that
// sentence true is to fail here when the two disagree, rather than to leave an
// example the index does not name and nothing to say so.
//
// The link is what is matched and not the prose, because the link is the part
// that has to be a real path: an index whose row points at a directory that is
// not there is broken for a reader on the forge, and one missing a row for a
// directory that is there is an example nobody finds.
//
// The precedent is internal/scaffold/derive_test.go, which pins docs/cli/SPEC.md's
// arithmetic against the copybook it is stated over rather than against a number
// somebody retypes.
func TestTheIndexNamesEveryExample(t *testing.T) {
	t.Parallel()

	index := string(readFile(t, indexName))

	linked := map[string]bool{}

	for _, example := range examples(t) {
		// The form a Markdown link to a directory takes, which is what the
		// table's first column holds: `[`ledger/`](ledger)`. The trailing
		// slash is a reader's convention and not part of the path, so both
		// spellings count.
		if strings.Contains(index, "]("+example+")") || strings.Contains(index, "]("+example+"/)") {
			linked[example] = true

			continue
		}

		t.Errorf("%s does not link to the %s example: an example the index does not name is one a reader does not find, and this table is the only thing here that does not read the tree",
			indexName, example)
	}

	// And the other direction, which is the one that goes wrong on a rename: a
	// row left behind pointing at a directory that has moved reads as an
	// example and is a broken link.
	for _, link := range indexLinks(index) {
		if linked[link] {
			continue
		}

		if _, err := os.Stat(filepath.Join(link, manifestName)); errors.Is(err, fs.ErrNotExist) {
			t.Errorf("%s links to %q as an example and nothing there carries a %s", indexName, link, manifestName)
		} else if err != nil {
			t.Fatalf("checking what %s links to at %q: %v", indexName, link, err)
		}
	}
}

// indexLinkTarget matches the target of a Markdown inline link whose text is a
// bare directory name in code ticks — the shape the index's first column uses,
// and narrow enough that the prose links everywhere else in the file are not
// mistaken for entries in the table.
var indexLinkTarget = regexp.MustCompile("\\[`([^`]+)/`\\]\\(([^)]+)\\)")

// indexLinks is what the index's example table points at, with the trailing
// slash a reader's convention adds taken back off.
func indexLinks(index string) []string {
	var found []string

	for _, match := range indexLinkTarget.FindAllStringSubmatch(index, -1) {
		target := strings.TrimSuffix(match[2], "/")

		// A link out of this directory is prose rather than a row: the table
		// names examples, which are underneath it.
		if strings.HasPrefix(target, "..") || strings.HasPrefix(target, "/") || strings.Contains(target, "://") {
			continue
		}

		found = append(found, target)
	}

	return found
}

// writeRecord writes a `cpybkc.gen.json` naming files, in the form cpybkc reads:
// version 1, project-root-relative slash-separated paths, sorted.
//
// Written out rather than taken from internal/generate, because this directory
// asserts against cpybkc from the outside — the record is a file a person can
// read and a next run depends on, and a test that built it with the same code
// that reads it would agree with a change to both.
func writeRecord(t *testing.T, path string, files []string) {
	t.Helper()

	files = slices.Clone(files)
	slices.Sort(files)

	body, err := json.MarshalIndent(struct {
		Version int      `json:"version"`
		Files   []string `json:"files"`
	}{Version: 1, Files: files}, "", "  ")
	if err != nil {
		t.Fatalf("encoding the record for %s: %v", path, err)
	}

	if err := os.WriteFile(path, append(body, '\n'), 0o644); err != nil {
		t.Fatalf("writing %s: %v", path, err)
	}
}

// readable is how long a generated file may be and still be printed whole when
// it disagrees with what is checked in.
//
// The files an example generates are not all the same size and do not want the
// same diagnostic. A diagram is under two hundred lines, and a reviewer
// reading a failure wants to see what the diagram became — printing both sides
// means the new document comes out of the test's own output, and what changed
// about the picture is legible in the failure rather than only after
// regenerating. A generated file tier runs to several thousand lines: an emitter
// changing is the ordinary reason this test fires rather than the rare one, and
// a failure that dumps two copies of it is one nobody reads.
//
// So the rule is the file's length rather than its name, and the number is where
// two copies stop being something a person reads in a scrollback.
const readable = 300

// difference is how two versions of one generated file disagree, as a
// diagnostic: both of them where the file is short enough to read, and where it
// is not, the first line they differ on.
//
// Nothing is lost by the short form — regenerating is three commands, and
// README.md is where they are written down.
func difference(got, want string) string {
	gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want, "\n")

	const regenerate = "\n\nRegenerate it with the commands in example/README.md and commit the result."

	if lines(gotLines) <= readable && lines(wantLines) <= readable {
		return fmt.Sprintf("\n--- generated ---\n%s\n--- checked in ---\n%s\n---%s", got, want, regenerate)
	}

	for i := range min(len(gotLines), len(wantLines)) {
		if gotLines[i] != wantLines[i] {
			return fmt.Sprintf("\nline %d\n got: %s\nwant: %s%s", i+1, gotLines[i], wantLines[i], regenerate)
		}
	}

	return fmt.Sprintf("\nthe first %d lines agree and the generated file has %d of them against the %d checked in%s",
		min(lines(gotLines), lines(wantLines)), lines(gotLines), lines(wantLines), regenerate)
}

// lines is how many lines a split file actually has.
//
// Every file cpybkc writes ends in a newline, and splitting one on "\n" leaves a
// trailing empty element that is not a line. Counting it would put a 300-line
// file at 301 and outside a [readable] budget the constant says admits it, and
// would report every count in the message above one too high.
func lines(split []string) int {
	if n := len(split); n > 0 && split[n-1] == "" {
		return n - 1
	}

	return len(split)
}

// examples is every worked example in this directory, by slash-separated path
// relative to it.
//
// An example is a directory carrying a manifest, which is the whole of what
// makes one: each is a self-contained cpybkc project, so the tests below need
// nothing about a new example written down here to cover it. Adding one is
// adding a directory.
//
// It is a listing rather than a list, for the reason [inputs] is: a list would
// be a second statement of what this directory holds, and the one failure mode
// worth ruling out is an example that quietly stops being asserted.
//
// **At any depth**, which is not the same rule as "a directory here", and the
// difference is what makes that claim true. A manifest one level further down —
// `payroll/v1/cpybkc.json`, an ordinary shape for a format with variants — would
// be an example a top-level listing skipped in silence, while the pipeline's own
// discovery found the module beside it: `.dagger`'s exampleModuleDirs globs
// `**/go.mod` at any depth, so a nested example's conversion would be compiled
// and linted and its generated tree never compared. Two rules over one directory
// that disagree about what an example is are worse than either rule.
//
// The walk stops at an example rather than descending through it. Everything
// under a manifest belongs to that project — its copybooks, the directories its
// generators write into, a conversion module beside them — and none of it is a
// second example. That is also what keeps a `cpybkc.json` appearing in generated
// output from being discovered as a project of its own.
func examples(t *testing.T) []string {
	t.Helper()

	var found []string

	err := filepath.WalkDir(".", func(path string, entry fs.DirEntry, err error) error {
		switch {
		case err != nil:
			return err
		case !entry.IsDir():
			return nil
		case path == ".":
			// This directory holds the examples and is not one. A manifest
			// here would make it a project of its own, which README.md says
			// it deliberately is not — and stopping the walk on it would
			// report the tree as empty.
			return nil
		}

		if _, err := os.Stat(filepath.Join(path, manifestName)); err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}

			return err
		}

		found = append(found, filepath.ToSlash(path))

		return fs.SkipDir
	})
	if err != nil {
		t.Fatalf("looking for the examples: %v", err)
	}

	if len(found) == 0 {
		t.Fatalf("nothing under this directory carries a %s, and this test asserts over the ones that do", manifestName)
	}

	slices.Sort(found)

	return found
}

// generators is an example's `generators` array, read rather than written down.
//
// Which generators an example runs, what they are called and where each one
// writes are facts its `cpybkc.json` already states, and a second copy of them
// here is one somebody would have to remember to update — a generator added to a
// manifest and not to this file is output nothing asserts, which is the failure
// this whole directory exists to catch, arrived at from the inside.
func generators(t *testing.T, dir string) []generator {
	t.Helper()

	path := filepath.Join(dir, manifestName)

	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}

	var manifest struct {
		Generators []generator `json:"generators"`
	}

	if err := json.Unmarshal(body, &manifest); err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}

	if len(manifest.Generators) == 0 {
		t.Fatalf("%s names no generators", path)
	}

	for _, gen := range manifest.Generators {
		if gen.Name == "" || gen.Out == "" {
			t.Fatalf("%s has a generator entry missing a name or an out directory: %+v", path, gen)
		}
	}

	return manifest.Generators
}

// outputDirs is the set of directories the manifest's generators write into,
// deduplicated: two generators are allowed to share one, and walking it twice
// would say nothing a walk once does not.
func outputDirs(gens []generator) []string {
	var dirs []string

	for _, gen := range gens {
		if !slices.Contains(dirs, gen.Out) {
			dirs = append(dirs, gen.Out)
		}
	}

	slices.Sort(dirs)

	return dirs
}

// pluginName is the executable cpybkc resolves a manifest name to, which is the
// whole of how a generator is identified.
func pluginName(name string) string {
	return "cpybkc-gen-" + name
}

// inputs is what a caller writes in one example: the manifest, the layout and
// the copybooks the layout names.
//
// It is a listing of that directory rather than a list written down, so that a
// copybook added to an example and never copied into the run is a failure
// rather than a file the assertion quietly stops covering.
func inputs(t *testing.T, dir string) []string {
	t.Helper()

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading %s: %v", dir, err)
	}

	var found []string

	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}

		name := entry.Name()
		if name == manifestName || filepath.Ext(name) == ".sexpr" || filepath.Ext(name) == ".cpy" {
			found = append(found, name)
		}
	}

	slices.Sort(found)

	return found
}

// generatedTree is everything cpybkc writes for this project, by slash-separated
// path relative to dir: the record beside the manifest, and every generator's
// output directory.
//
// A `_test.go` file may or may not be one, and the `// Code generated … DO NOT
// EDIT.` header is what tells them apart. `cpybkc-gen-go` writes a test file of
// its own — the record tier, one case per record carrying the bytes it reads as
// a literal — and that is output, pinned byte for byte like everything else.
// The hand-written round-trip assertions beside it are not: they run inside the
// generated package because a credit posting's retained slack is unexported,
// and nothing regenerates them.
func generatedTree(t *testing.T, dir string, outs []string) map[string]string {
	t.Helper()

	found := map[string]string{}

	if body, err := os.ReadFile(filepath.Join(dir, recordName)); err == nil {
		found[recordName] = string(body)
	} else if !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("reading %s: %v", filepath.Join(dir, recordName), err)
	}

	for _, out := range outs {
		err := filepath.WalkDir(filepath.Join(dir, out), func(path string, entry fs.DirEntry, err error) error {
			switch {
			case err != nil:
				return err
			case entry.IsDir():
				return nil
			}

			body, err := os.ReadFile(path)
			if err != nil {
				return err
			}

			if strings.HasSuffix(entry.Name(), "_test.go") && !bytes.HasPrefix(body, []byte(generatedHeader)) {
				return nil
			}

			rel, err := filepath.Rel(dir, path)
			if err != nil {
				return err
			}

			found[filepath.ToSlash(rel)] = string(body)

			return nil
		})
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			t.Fatalf("walking %s: %v", filepath.Join(dir, out), err)
		}
	}

	return found
}

// build builds one of this repository's commands into bin.
//
// The generators are built under the names the CLI looks for on PATH, and the
// tree under test is what all of them are built from: a run against the
// generator somebody installed months ago would assert nothing about the pull
// request making it.
func build(t *testing.T, root, bin, pkg, name string) {
	t.Helper()

	cmd := exec.Command("go", "build", "-o", filepath.Join(bin, executable(name)), pkg)
	cmd.Dir = root

	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("building %s: %v\n%s", pkg, err, out)
	}
}

// stubOutput is the one file the stub generator writes: the descriptor it was
// handed, copied into its own output directory.
const stubOutput = "descriptor.bin"

// stubSource is a generator that answers one question — what bytes was I handed?
//
// It is a program rather than a fixture because a generator is discovered on
// PATH and run as a process, and interposing anything else would be asserting
// against a pipeline this example does not have. It reads only the two flags the
// contract requires of every plugin, ignores the options cpybkc passes it, and
// writes one file beneath `--out`, which is where a plugin's output belongs.
const stubSource = `package main

import (
	"fmt"
	"os"
	"path/filepath"
)

// output is the file this generator writes, substituted in by the test so that
// the two sides cannot drift.
const output = "OUTPUT_FILE"

func main() {
	var descriptor, out string

	args := os.Args[1:]
	for i := 0; i < len(args); i++ {
		if i+1 >= len(args) {
			break
		}

		switch args[i] {
		case "--descriptor":
			descriptor, i = args[i+1], i+1
		case "--out":
			out, i = args[i+1], i+1
		}
	}

	if descriptor == "" || out == "" {
		fmt.Fprintln(os.Stderr, "error: --descriptor and --out are both required")
		os.Exit(1)
	}

	body, err := os.ReadFile(descriptor)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: reading the descriptor: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(filepath.Join(out, output), body, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "error: writing the descriptor out: %v\n", err)
		os.Exit(1)
	}
}
`

// buildStub builds the stub generator into bin under one of the names cpybkc
// will look for.
//
// It is built in a module of its own rather than added to this repository's
// command tree: it is a fake generator, and a fake generator checked in beside
// the two real ones is something an adopter reading `cmd/` would have to be told
// to ignore.
func buildStub(t *testing.T, bin, name string) {
	t.Helper()

	dir := t.TempDir()

	source := strings.ReplaceAll(stubSource, "OUTPUT_FILE", stubOutput)

	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(source), 0o644); err != nil {
		t.Fatalf("writing the stub generator: %v", err)
	}

	for _, args := range [][]string{
		{"mod", "init", "cpybkcexamplestub"},
		{"build", "-o", filepath.Join(bin, executable(name)), "."},
	} {
		cmd := exec.Command("go", args...)
		cmd.Dir = dir

		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("go %s for the stub generator: %v\n%s", strings.Join(args, " "), err, out)
		}
	}
}

// executable is a command's file name on this operating system.
func executable(name string) string {
	if runtime.GOOS == "windows" {
		return name + ".exe"
	}

	return name
}

// copyFile copies one input into the directory the run is made in.
//
// The run is made against a copy rather than against this directory because
// generating writes: a run in place would leave the working tree holding output
// that had not been reviewed, and a failure would be indistinguishable from
// somebody having edited the generated code by hand.
func copyFile(t *testing.T, from, to string) {
	t.Helper()

	if err := os.WriteFile(to, readFile(t, from), 0o644); err != nil {
		t.Fatalf("writing %s: %v", to, err)
	}
}

// readFile is os.ReadFile with the failure already reported.
func readFile(t *testing.T, name string) []byte {
	t.Helper()

	body, err := os.ReadFile(name)
	if err != nil {
		t.Fatalf("reading %s: %v", name, err)
	}

	return body
}

// repoRoot is the directory holding go.mod, walked up to from this test's own.
func repoRoot(t *testing.T) string {
	t.Helper()

	dir, err := os.Getwd()
	if err != nil {
		t.Fatalf("working directory: %v", err)
	}

	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}

		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatalf("no go.mod above %s", dir)
		}

		dir = parent
	}
}
